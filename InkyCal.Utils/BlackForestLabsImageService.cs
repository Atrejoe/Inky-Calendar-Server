using System;
using System.Collections.Generic;
using System.Linq;
using System.Net.Http;
using System.Threading;
using System.Threading.Tasks;
using InkyCal.Utils.BlackForestLabs.Client;
using InkyCal.Utils.BlackForestLabs.Client.Models;
using Microsoft.Kiota.Abstractions;
using Microsoft.Kiota.Abstractions.Authentication;
using Microsoft.Kiota.Abstractions.Serialization;
using Microsoft.Kiota.Http.HttpClientLibrary;

namespace InkyCal.Utils
{
	/// <summary>
	/// Generates images with Black Forest Labs' FLUX.2 models through the BFL API.
	/// </summary>
	/// <remarks>
	/// <para>BFL offers no .NET SDK. The client in <c>BlackForestLabs/Client</c> is generated by Kiota from BFL's OpenAPI spec,
	/// and the <c>update-bfl-client</c> GitHub workflow regenerates it when the spec changes.</para>
	/// <para>BFL has no language model, so composing the image prompt is delegated to another provider (see constructor).</para>
	/// </remarks>
	public sealed class BlackForestLabsImageService : ImageGenerationServiceBase
	{
		/// <summary>Model used when none is configured: about $0.014 per 1 MP image (2026-11).</summary>
		public const string DefaultModel = "flux-2-klein-9b";

		/// <summary>The supported models, the BFL endpoint names.</summary>
		public static readonly string[] SupportedModels = ["flux-2-klein-4b", "flux-2-klein-9b", "flux-2-pro", "flux-2-flex", "flux-2-max"];

		private static readonly HttpClient _httpClient = new();

		private readonly string _apiKey;
		private readonly string _model;
		private readonly int _width;
		private readonly int _height;
		private readonly IChatCompletionService _promptService;
		private readonly TimeSpan _pollInterval;
		private readonly TimeSpan _timeout;
		private readonly Lazy<BflApiClient> _client;

		/// <summary>
		/// Initializes a new instance of the <see cref="BlackForestLabsImageService"/> class.
		/// When <paramref name="apiKey"/> is null or empty <see cref="IsAvailable"/> returns <c>false</c>.
		/// </summary>
		/// <param name="apiKey">The BFL API key.</param>
		/// <param name="model">One of <see cref="SupportedModels"/>, defaults to <see cref="DefaultModel"/>.</param>
		/// <param name="width">Image width, a multiple of 16; defaults to 1024.</param>
		/// <param name="height">Image height, a multiple of 16; defaults to 768.</param>
		/// <param name="promptService">
		/// Composes the image prompt from the calendar events. When <c>null</c> or unavailable,
		/// the system and user prompt are passed to FLUX as-is (FLUX.2 handles long, descriptive prompts well).
		/// </param>
		public BlackForestLabsImageService(string apiKey, string model = null, int? width = null, int? height = null, IChatCompletionService promptService = null)
			: this(apiKey, model, width, height, promptService, baseUrl: null, pollInterval: TimeSpan.FromSeconds(1), timeout: TimeSpan.FromMinutes(3))
		{
		}

		/// <summary>Initializes a new instance against a custom endpoint, used for testing.</summary>
		/// <param name="apiKey">The BFL API key.</param>
		/// <param name="model">The model.</param>
		/// <param name="width">Image width.</param>
		/// <param name="height">Image height.</param>
		/// <param name="promptService">Composes the image prompt.</param>
		/// <param name="baseUrl">Overrides the BFL API endpoint.</param>
		/// <param name="pollInterval">Delay between polls for the result.</param>
		/// <param name="timeout">Maximum time to wait for the result.</param>
		internal BlackForestLabsImageService(string apiKey, string model, int? width, int? height, IChatCompletionService promptService, Uri baseUrl, TimeSpan pollInterval, TimeSpan timeout)
		{
			_apiKey = apiKey;
			_model = string.IsNullOrWhiteSpace(model) ? DefaultModel : model.Trim().ToLowerInvariant();
			if (!SupportedModels.Contains(_model))
				throw new NotSupportedException($"Unsupported Black Forest Labs model '{model}', use one of: {string.Join(", ", SupportedModels)}.");

			_width = RoundTo16(width ?? 1024);
			_height = RoundTo16(height ?? 768);
			_promptService = promptService;
			_pollInterval = pollInterval;
			_timeout = timeout;

			_client = new Lazy<BflApiClient>(() =>
			{
				var authentication = new BflKeyAuthenticationProvider(_apiKey, trustedHost: baseUrl?.Host);
				var adapter = new HttpClientRequestAdapter(authentication, httpClient: _httpClient);
				if (baseUrl is not null)
					adapter.BaseUrl = baseUrl.ToString().TrimEnd('/');
				return new BflApiClient(adapter);
			});
		}

		/// <summary>
		/// Adds the API key (header <c>x-key</c>) only to https requests to BFL hosts (<c>api.bfl.ai</c> and regional
		/// endpoints such as <c>api.eu1.bfl.ai</c> returned as polling url), or to <paramref name="trustedHost"/> (testing).
		/// </summary>
		private sealed class BflKeyAuthenticationProvider(string apiKey, string trustedHost) : IAuthenticationProvider
		{
			public Task AuthenticateRequestAsync(RequestInformation request, Dictionary<string, object> additionalAuthenticationContext = null, CancellationToken cancellationToken = default)
			{
				ArgumentNullException.ThrowIfNull(request);
				var uri = request.URI;
				var trusted = (uri.Scheme == Uri.UriSchemeHttps
						&& (uri.Host.Equals("bfl.ai", StringComparison.OrdinalIgnoreCase) || uri.Host.EndsWith(".bfl.ai", StringComparison.OrdinalIgnoreCase)))
					|| (trustedHost is not null && uri.Host.Equals(trustedHost, StringComparison.OrdinalIgnoreCase));

				if (!trusted)
					throw new InvalidOperationException($"Refusing to send the Black Forest Labs API key to '{uri.Host}'.");

				request.Headers.Add("x-key", apiKey);
				return Task.CompletedTask;
			}
		}

		private static int RoundTo16(int value) => Math.Max(64, (int)Math.Round(value / 16d, MidpointRounding.AwayFromZero) * 16);

		/// <inheritdoc/>
		public override string ProviderName => "Black Forest Labs";

		/// <inheritdoc/>
		public override bool IsAvailable => !string.IsNullOrEmpty(_apiKey);

		/// <inheritdoc/>
		protected override Task<string> GetChatCompletionCoreAsync(string systemPrompt, string userPrompt, CancellationToken cancellationToken)
			=> _promptService is null or IImageGenerationService { IsAvailable: false }
				? Task.FromResult($"{systemPrompt}{Environment.NewLine}{Environment.NewLine}{userPrompt}")
				: _promptService.GetChatCompletionAsync(systemPrompt, userPrompt, cancellationToken);

		/// <inheritdoc/>
		protected override async Task<byte[]> GenerateImageCoreAsync(string prompt, CancellationToken cancellationToken)
		{
			var task = await SubmitAsync(prompt, cancellationToken);
			if (string.IsNullOrEmpty(task?.PollingUrl))
				throw new InvalidOperationException($"{ProviderName} did not return a polling url.");

			var sampleUrl = await PollAsync(task.PollingUrl, cancellationToken);

			// The sample url is a signed, short-lived url that requires no authentication
			return await _httpClient.GetByteArrayAsync(new Uri(sampleUrl), cancellationToken);
		}

		private async Task<AsyncResponse> SubmitAsync(string prompt, CancellationToken cancellationToken)
		{
			var v1 = _client.Value.V1;
			var jpeg = OutputFormat.Jpeg;

			Flux2KleinInputs Klein() => new()
			{
				Prompt = prompt,
				Width = new() { Integer = _width },
				Height = new() { Integer = _height },
				OutputFormat = jpeg,
			};
			Flux2Inputs Pro() => new()
			{
				Prompt = prompt,
				Width = new() { Integer = _width },
				Height = new() { Integer = _height },
				OutputFormat = jpeg,
			};

			return _model switch
			{
				"flux-2-klein-4b" => (await v1.Flux2Klein4b.PostAsync(Klein(), cancellationToken: cancellationToken))?.AsyncResponse,
				"flux-2-klein-9b" => (await v1.Flux2Klein9b.PostAsync(Klein(), cancellationToken: cancellationToken))?.AsyncResponse,
				"flux-2-pro" => (await v1.Flux2Pro.PostAsync(Pro(), cancellationToken: cancellationToken))?.AsyncResponse,
				"flux-2-max" => (await v1.Flux2Max.PostAsync(Pro(), cancellationToken: cancellationToken))?.AsyncResponse,
				"flux-2-flex" => (await v1.Flux2Flex.PostAsync(new Flux2FlexInputs
				{
					Prompt = prompt,
					Width = new() { Integer = _width },
					Height = new() { Integer = _height },
					OutputFormat = jpeg,
				}, cancellationToken: cancellationToken))?.AsyncResponse,
				_ => throw new NotSupportedException(_model),
			};
		}

		/// <summary>
		/// Polls the (regional) polling url until the task is ready, returns the url of the generated sample.
		/// </summary>
		private async Task<string> PollAsync(string pollingUrl, CancellationToken cancellationToken)
		{
			using var timeout = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
			timeout.CancelAfter(_timeout);

			while (true)
			{
				await Task.Delay(_pollInterval, timeout.Token);

				// A new request builder per poll: reusing one drops the query string (the task id) on subsequent requests.
				var response = await _client.Value.V1.Get_result.WithUrl(pollingUrl).GetAsync(cancellationToken: timeout.Token);
				var status = response?.SettledCostResultResponse?.Status ?? response?.ResultResponse?.Status;
				var result = response?.SettledCostResultResponse?.Result ?? response?.ResultResponse?.Result;

				switch (status)
				{
					case StatusResponse.Ready:
						return (result as UntypedObject)?.GetValue().TryGetValue("sample", out var sample) == true
							&& sample is UntypedString { } url
							&& !string.IsNullOrEmpty(url.GetValue())
							? url.GetValue()
							: throw new InvalidOperationException($"{ProviderName} reported the image ready, but returned no sample url.");
					case StatusResponse.Pending or StatusResponse.Reasoning or StatusResponse.Generating:
						continue;
					default:
						throw new InvalidOperationException($"{ProviderName} image generation failed with status '{status}'.");
				}
			}
		}
	}
}
